    <div class="purpose-content">
      <h3 style="color: #8b0000; font-size: 24px; margin-bottom: 20px">
        Digital Cultural Preservation Through Food
      </h3>
      <p style="font-size: 18px; line-height: 1.8; margin-bottom: 30px">
        "Taste of Ethiopia" is not merely a restaurant management system with
        an Ethiopian menu. It is a
        <strong>digital cultural preservation and education platform</strong>
        that uses food as its primary medium. Its core purpose is to
        safeguard, celebrate, and share the rich, diverse culinary heritage of
        Ethiopia with both a domestic and global audience.
      </p>
      <p style="font-size: 18px; line-height: 1.8">
        The primary purpose is to serve as a bridge between users and the
        deep-rooted culinary traditions of Ethiopia, transforming the act of
        ordering food into an immersive journey of discovery, learning, and
        cultural connection. It aims to preserve endangered food knowledge,
        educate the next generation, and celebrate the unique stories behind
        every dish, ensuring these traditions are not lost but savored and
        appreciated worldwide.
      </p>
    </div>
  </section>

