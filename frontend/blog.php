               Bulla is a traditional food of the Sidama region in Ethiopia, made from the starchy pulp of the enset plant (false banana).</p>
           </div>
           <div class="blog-card-excerpt full-text" style="display: none">
             <p>
               It is a finely powdered, nutritious flour that can be mixed with water or milk to make a smooth porridge or drink.</p>
             <p>
               The preparation is an art. Teff flour is mixed with water and fermented for up to three days, giving injera its signature tangy flavor and airy texture. It’s then poured onto a large clay griddle called a <em>mitad</em> and cooked until spongy and dotted with holes.
             </p>
             <p>
                Bulla is often eaten for breakfast or during special occasions, and it is highly valued for its energy and nutritional content.</p>
             <p>
               Short and Clear Steps

              1.Extract the starchy pulp from the enset corm.
              2. Squeeze and dry the pulp to get fine powder (bulla).
              3. Boil water or milk in a pot.
              4. Gradually add bulla powder while stirring continuously.
              5. Stir until a smooth, thick porridge forms.
              6. Serve hot, plain or with spiced butter or honey. </p>
