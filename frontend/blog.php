           </div>
           <div class="blog-card-excerpt full-text" style="display: none">
             <p>
               It is often served with melted and clarified butter, known as dhadhaa, and is a staple in Oromo meals.  </p>
             <p>
              The dish is prepared by grinding barley flour and boiling it in a clay pot, then adding water and other ingredients. Marqaa is typically eaten with injera, a teff-based flatbread, and is a favorite among the Oromo people. </p>
             <p>
              ·  Everyday staple food
              ·  Easy and quick to prepare
              ·  High energy food for farmers and workers
              ·  Symbol of simplicity and self-sufficiency</p>
             <p>
              Steps to Prepare Marqaa

             1.Boil water in a pot.
             2.Reduce the heat.
             3.Add flour slowly while stirring continuously.
             4.Keep stirring until the mixture becomes thick and smooth.
             5.Add salt if needed and mix well.
             6.Shape the Marqaa in a bowl.
             7.Make a small hole in the center and add butter or oil.</p>
          
