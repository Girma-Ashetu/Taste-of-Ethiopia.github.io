           <div class="blog-card-excerpt preview-text">
             <p>
              Tihlo is the most iconic traditional food of the Tigray region in Ethiopia. </p>
           </div>
           <div class="blog-card-excerpt full-text" style="display: none">
             <p>
               It is made from roasted barley flour that is kneaded into small dough balls and eaten with a spicy meat or vegetable sauce.  </p>
             <p>
               Tihlo is traditionally eaten by hand, often during gatherings or special occasions. It is highly nutritious and considered a symbol of Tigrayan culture.</p>
             <p>
               Steps to Prepare

             1.Roast barley flour lightly until aromatic.
             2.Mix the roasted flour with a little water to form a smooth dough.
             3.Roll the dough into small bite-sized balls.
             4.Prepare a spicy sauce (usually meat or vegetable-based).
             5.Serve the dough balls with the sauce.
             6.Eat by dipping the dough balls into the sauce.</p>
            
